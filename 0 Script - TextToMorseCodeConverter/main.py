def text_to_morse(message):
    morse_message = ""
    for char in message:
        if char == "\n":
            morse_message += "\n"
        elif char == " ":
            morse_message += "/ "
        else:
            morse_message += morse.get(char.upper(), "") + " "

    return morse_message.strip()


